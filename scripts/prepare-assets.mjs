// Prepares optimized web assets from the original brand/product files.
// Originals are never modified. Run: npm run assets
import sharp from "sharp";
import { createHash } from "node:crypto";
import { mkdir, readdir, unlink, writeFile } from "node:fs/promises";
import path from "node:path";

sharp.cache(false);
const root = process.cwd();
const parent = path.resolve(root, "..");
const video = path.join(parent, "sabili-video");
const out = (...p) => path.join(root, "public", "images", ...p);

async function ensure(dir) {
  await mkdir(dir, { recursive: true });
}

/**
 * Writes `<base>.<contenthash>.<ext>` and removes older versions of the same base.
 * A new file content always gets a new URL, so browsers and the Next.js image
 * cache can never keep showing an outdated card or logo.
 */
async function writeHashed(buffer, dir, base, ext) {
  await ensure(dir);
  const hash = createHash("sha256").update(buffer).digest("hex").slice(0, 8);
  const name = `${base}.${hash}.${ext}`;
  for (const f of await readdir(dir)) {
    if ((f === `${base}.${ext}` || (f.startsWith(`${base}.`) && f.endsWith(`.${ext}`) && f.split(".").length === 3)) && f !== name) {
      await unlink(path.join(dir, f));
    }
  }
  await writeFile(path.join(dir, name), buffer);
  return name;
}

async function writeManifest(file, exportName, typeName, entries) {
  const lines = Object.entries(entries).map(([k, v]) => `  "${k}": { src: "${v.src}", width: ${v.width}, height: ${v.height} },`);
  await writeFile(
    path.join(root, "src", "lib", file),
    `// Generated by scripts/prepare-assets.mjs — do not edit by hand.\nexport const ${exportName} = {\n${lines.join("\n")}\n} as const;\n\nexport type ${typeName} = keyof typeof ${exportName};\n`,
  );
}

