/** Rounded corners like the printed cards (radius ≈ 7% of the short side). */
async function roundCorners(buffer) {
  const { width, height } = await sharp(buffer).metadata();
  const r = Math.round(Math.min(width, height) * 0.07);
  const mask = Buffer.from(`<svg width="${width}" height="${height}"><rect width="${width}" height="${height}" rx="${r}" ry="${r}"/></svg>`);
  return sharp(buffer).composite([{ input: mask, blend: "dest-in" }]).png().toBuffer();
}

/** Crops away fully transparent margins only (sharp's trim() would also eat solid card colour). */
async function cropTransparent(file) {
  const { data, info } = await sharp(file).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let minX = info.width, minY = info.height, maxX = -1, maxY = -1;
  for (let y = 0; y < info.height; y++) {
    for (let x = 0; x < info.width; x++) {
      if (data[(y * info.width + x) * 4 + 3] > 8) {
        if (x < minX) minX = x;
        if (x > maxX) maxX = x;
        if (y < minY) minY = y;
        if (y > maxY) maxY = y;
      }
    }
  }
  // Inset by 3px: the exported files carry a faint light edge (and a sliver of a neighbour on one card).
  const inset = 3;
  return sharp(file)
    .ensureAlpha()
    .extract({ left: minX + inset, top: minY + inset, width: maxX - minX + 1 - inset * 2, height: maxY - minY + 1 - inset * 2 });
}

async function cardImages() {
  await ensure(out("cards"));
  for (const card of cards) {
    let img = await cropTransparent(path.join(root, card.src));
    if (card.rotate) img = sharp(await img.png().toBuffer()).rotate(card.rotate);
    // 2× upscale so cards stay crisp on high-density phone screens.
    const meta = await sharp(await img.png().toBuffer()).metadata();
    const scaled = await sharp(await img.png().toBuffer())
      .resize({ width: meta.width * 2, kernel: "lanczos3" })
      .png()
      .toBuffer();
    const { data, info } = await sharp(await roundCorners(scaled))
      .webp({ quality: 92, alphaQuality: 100, smartSubsample: true })
      .toBuffer({ resolveWithObject: true });
    const file = await writeHashed(data, out("cards"), card.name, "webp");
    manifest[card.name] = { src: `/images/cards/${file}`, width: info.width, height: info.height };
  }
  await writeManifest("card-images.ts", "CARD_IMAGES", "CardName", manifest);
}
