// ---------- Logos: flat recolor from the real logo shapes ----------
async function recolorFromMask(input, { threshold, color, width, file, invertLuma = false }) {
  const img = sharp(input, { limitInputPixels: false }).ensureAlpha();
  const { data, info } = await img.raw().toBuffer({ resolveWithObject: true });
  const outBuf = Buffer.alloc(info.width * info.height * 4);
  for (let i = 0; i < info.width * info.height; i++) {
    const r = data[i * 4], g = data[i * 4 + 1], b = data[i * 4 + 2], a = data[i * 4 + 3];
    // gold pixels: bright and warm (r high, b lower)
    const luma = 0.299 * r + 0.587 * g + 0.114 * b;
    const warm = r - b;
    let on = invertLuma ? a > 128 : luma > threshold && warm > 40 && a > 128;
    outBuf[i * 4] = color[0];
    outBuf[i * 4 + 1] = color[1];
    outBuf[i * 4 + 2] = color[2];
    outBuf[i * 4 + 3] = on ? 255 : 0;
  }
  const result = sharp(outBuf, { raw: { width: info.width, height: info.height, channels: 4 } })
    .trim()
    .median(3)
    .resize({ width })
    .png({ compressionLevel: 9 });
  if (file) return result.toFile(file);
  return result.toBuffer({ resolveWithObject: true });
}

/**
 * The Sabili mask was traced from a video frame of the box lid held at an angle
 * (sabili-video/assets_src/lid.png), so the WHOLE logo — arch and word alike — is skewed:
 * horizontal strokes slope down ~5.5° and vertical strokes lean ~5°. Measured with a
 * projection-profile search (max variance of row/column sums), identical for arch and word.
 *
 * Distortion model:  x_img = x + V·y,  y_img = H·x + y.  We apply its exact inverse to the
 * whole mask in one step, so proportions are preserved (no per-part rotation, no stretching).
 */
const SKEW_H = 0.096; // dy/dx of lines that should be horizontal
const SKEW_V = -0.0875; // dx/dy of lines that should be vertical

async function straightenedSabiliMask() {
  const trimmed = await sharp(path.join(video, "public", "sabili-logo-mask.png")).ensureAlpha().trim().png().toBuffer();
  const det = 1 - SKEW_V * SKEW_H;
  const inverse = [1 / det, -SKEW_V / det, -SKEW_H / det, 1 / det];
  return sharp(trimmed)
    .affine(inverse, { background: { r: 0, g: 0, b: 0, alpha: 0 }, interpolator: sharp.interpolators.bicubic })
    .png()
    .toBuffer();
}

async function logos() {
  await ensure(out("brand"));
  const mishkatSrc = path.join(video, "public", "mishkat-logo-trim.png");
  await recolorFromMask(mishkatSrc, { threshold: 90, color: [10, 10, 10], width: 640, file: out("brand", "mishkat-ink.png") });
  await recolorFromMask(mishkatSrc, { threshold: 90, color: [217, 175, 87], width: 640, file: out("brand", "mishkat-gold.png") });
  const sabiliMask = await straightenedSabiliMask();
  const brand = {};
  for (const [key, color] of [
    ["sabili-gold", [217, 175, 87]],
    ["sabili-yellow", [255, 210, 0]],
  ]) {
    const { data, info } = await recolorFromMask(sabiliMask, { invertLuma: true, color, width: 520, file: null });
    const file = await writeHashed(data, out("brand"), key, "png");
    brand[key] = { src: `/images/brand/${file}`, width: info.width, height: info.height };
  }
  await writeManifest("brand-images.ts", "BRAND_IMAGES", "BrandImage", brand);
}

